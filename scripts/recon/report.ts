/** Renders the reconnaissance findings as readable markdown. */

import type { FrontendDiscovery } from './discover-frontend.ts';
import type { ProbeResult } from './probe-api.ts';
import type { CaptureResult } from './capture.ts';

interface Report {
  meta: Record<string, unknown>;
  frontend: FrontendDiscovery;
  probes: ProbeResult[];
  capture: CaptureResult;
}

const row = (cells: unknown[]): string => `| ${cells.join(' | ')} |`;

export function renderMarkdown(report: Report): string {
  const { meta, frontend, probes, capture } = report;
  const out: string[] = [];

  out.push('# Tennis TV reconnaissance report', '');
  out.push('_Generated by `npm run recon`. Do not edit by hand._', '');
  out.push(row(['Field', 'Value']), row(['---', '---']));
  for (const [key, value] of Object.entries(meta)) out.push(row([key, `\`${String(value)}\``]));
  out.push('');

  out.push('## How the front end gets its data', '');
  out.push(`- Rendering: **${frontend.rendering}**`);
  out.push(`- Entry bundle: \`${frontend.bundleUrl ?? 'not found'}\``);
  out.push(`- API base read from bundle: \`${frontend.apiBaseFromBundle ?? 'not found'}\``);
  out.push(
    `- Endpoint paths in bundle: ${frontend.endpointPathsFromBundle.map((p) => `\`${p}\``).join(', ')}`,
  );
  for (const note of frontend.notes) out.push(`- ${note}`);
  out.push('');

  out.push('## Endpoint / parameter probes', '');
  out.push(
    row(['Probe', 'Path', 'HTTP', 'Bytes', 'Shape', 'Items']),
    row(['---', '---', '---', '---', '---', '---']),
  );
  for (const probe of probes) {
    out.push(
      row([
        probe.label,
        `\`${probe.path}\``,
        probe.status,
        probe.bodyBytes,
        `\`${probe.topLevelShape}\``,
        probe.itemCount ?? '—',
      ]),
    );
  }
  out.push('');

  const cacheSample = probes.find((probe) => Object.keys(probe.cacheHeaders).length > 0);
  out.push('### Cache / freshness headers observed', '');
  out.push('```json');
  out.push(JSON.stringify(cacheSample?.cacheHeaders ?? {}, null, 2));
  out.push('```', '');

  out.push('## Tournaments', '');
  out.push(
    `Season window \`${capture.seasonWindow.from}\` → \`${capture.seasonWindow.to}\`: **${capture.tournamentCount}** tournaments.`,
  );
  out.push(
    `Identifier \`id:year\` unique: **${capture.tournamentIdUniqueness.unique}** (${capture.tournamentIdUniqueness.distinct}/${capture.tournamentIdUniqueness.total}).`,
  );
  out.push(`Phase breakdown: \`${JSON.stringify(capture.phaseBreakdown)}\``, '');

  out.push('### Tournament fields', '');
  out.push(fieldTable(capture.tournamentFields, capture.tournamentCount));
  out.push(
    '',
    '### `info` fields',
    '',
    fieldTable(capture.tournamentInfoFields, capture.tournamentCount),
  );
  out.push(
    '',
    '### `metadata` fields',
    '',
    fieldTable(capture.tournamentMetadataFields, capture.tournamentCount),
  );
  out.push('');

  out.push('### Marked as NOT shown on Tennis TV', '');
  if (capture.notShownTournaments.length === 0) {
    out.push('_None found in this window._');
  } else {
    out.push(row(['Start', 'Name', 'Type', 'broadcastText']), row(['---', '---', '---', '---']));
    for (const tournament of capture.notShownTournaments) {
      out.push(
        row([
          tournament.start,
          tournament.name,
          tournament.type ?? '',
          tournament.broadcastText ?? '',
        ]),
      );
    }
  }
  out.push('');

  out.push('## Matches', '');
  out.push('### Match fields (across every sampled tournament)', '');
  out.push(
    fieldTable(capture.matchFields, Math.max(...capture.matchSamples.map((s) => s.matchCount), 1)),
  );
  out.push('');
  out.push(`Aggregate \`Status\`: \`${JSON.stringify(capture.aggregateStatusTally)}\``);
  out.push(`Aggregate \`PulseStatus\`: \`${JSON.stringify(capture.aggregatePulseStatusTally)}\``);
  out.push(`Aggregate \`Reason\`: \`${JSON.stringify(capture.aggregateReasonTally)}\``, '');

  out.push('### Are match-level times published in advance?', '');
  out.push(
    row([
      'Tournament',
      'Starts',
      'Days out',
      'Phase',
      'OOP days',
      'Matches',
      'With MatchDate',
      'With time-of-day',
      'Midnight time',
      'NotBefore',
    ]),
  );
  out.push(row(['---', '---', '---', '---', '---', '---', '---', '---', '---', '---']));
  for (const sample of capture.matchSamples) {
    out.push(
      row([
        `${sample.tournament.name}${sample.tournament.notShown ? ' *(not shown)*' : ''}`,
        sample.tournament.start,
        sample.tournament.daysUntilStart,
        sample.tournament.phase,
        sample.tournament.oopDayCount,
        sample.matchCount,
        sample.withMatchDate,
        sample.withTimeOfDay,
        sample.withMidnightTime,
        sample.withNotBefore,
      ]),
    );
  }
  out.push('');

  out.push('### Per-tournament detail', '');
  for (const sample of capture.matchSamples) {
    out.push(
      `#### ${sample.tournament.name} ${sample.tournament.year} (id ${sample.tournament.id}, ${sample.tournament.phase})`,
      '',
    );
    out.push(
      `- request: \`${sample.request.path}\` → HTTP ${sample.request.status}, ${sample.request.bodyBytes} bytes`,
    );
    out.push(`- matches published: **${sample.matchesPublished}** (${sample.matchCount})`);
    out.push(
      `- MatchId unique within tournament: **${sample.matchIdUnique}**; sample: ${sample.matchIdSample.map((id) => `\`${id}\``).join(', ') || '—'}`,
    );
    out.push(`- Status: \`${JSON.stringify(sample.statusTally)}\``);
    out.push(`- PulseStatus: \`${JSON.stringify(sample.pulseStatusTally)}\``);
    out.push(`- Reason: \`${JSON.stringify(sample.reasonTally)}\``);
    out.push(
      `- distinct times of day (first 12): \`${JSON.stringify(sample.distinctTimesOfDay)}\``,
    );
    out.push(`- rounds: \`${JSON.stringify(sample.roundsSeen)}\``);
    out.push(`- courts: \`${JSON.stringify(sample.courtsSeen)}\``);
    out.push(`- match-level \`metadata\` present on: ${sample.matchLevelMetadataCount} match(es)`);
    out.push(
      `- venue utcOffset: \`${sample.tournament.utcOffset ?? 'absent'}\`; customRoute: \`${sample.tournament.customRoute ?? 'absent'}\``,
    );
    out.push('');
  }

  return `${out.join('\n')}\n`;
}

function fieldTable(fields: CaptureResult['matchFields'], total: number): string {
  const lines = [
    row(['Field', 'Present', 'Types', 'Nulls', 'Examples']),
    row(['---', '---', '---', '---', '---']),
  ];
  for (const field of fields) {
    const examples = field.examples
      .map((e) => JSON.stringify(e))
      .join(', ')
      .slice(0, 90);
    lines.push(
      row([
        `\`${field.key}\``,
        `${field.presentIn}/${total}`,
        field.types.join('|'),
        field.nullCount,
        examples ? `\`${examples}\`` : '',
      ]),
    );
  }
  return lines.join('\n');
}
