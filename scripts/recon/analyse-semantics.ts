/**
 * Step 4 of reconnaissance: work out what the fields actually MEAN.
 *
 * Runs against the raw payloads persisted by `npm run recon` (.recon-out/raw), so it
 * can be iterated on without re-fetching anything from Tennis TV.
 *
 *   npm run recon:semantics
 *
 * Specifically it establishes, from data rather than from the front-end bundle:
 *  - how an unpublished start time is represented
 *  - what NotBeforeISOTime / NotBeforeText mean and when they appear
 *  - the real Status / PulseStatus vocabulary and which record shapes carry which
 *  - whether MatchId is globally unique and stable enough to key match identity on
 *  - how competitors are represented
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { tally, uniqueness } from './lib/analyse.ts';

const RAW_DIR = join('.recon-out', 'raw');
const OUT_FILE = join('.recon-out', 'semantics.md');

interface RawMatch {
  MatchId?: string;
  MatchDate?: string;
  NotBeforeISOTime?: string;
  NotBeforeText?: string;
  NotBefore?: string;
  Status?: string;
  PulseStatus?: string;
  Reason?: string;
  CourtName?: string;
  CourtId?: number;
  Round?: { ShortName?: string; LongName?: string; RoundId?: number };
  RoundId?: number;
  PlayerTeam1?: Record<string, unknown>;
  PlayerTeam2?: Record<string, unknown>;
  TeamsInMatch?: unknown[];
  TournamentId?: number;
  TournamentYear?: number;
  metadata?: Record<string, unknown>;
  [key: string]: unknown;
}

interface Loaded {
  key: string;
  matches: RawMatch[];
}

const timeOfDay = (match: RawMatch): string => (match.MatchDate ?? '').slice(11, 19);
const hasNoPublishedTime = (match: RawMatch): boolean => {
  const time = timeOfDay(match);
  return !match.MatchDate || time === '' || time === '00:00:00';
};

async function load(): Promise<Loaded[]> {
  const files = (await readdir(RAW_DIR)).filter((f) => f.startsWith('matches-'));
  const out: Loaded[] = [];
  for (const file of files) {
    const body = JSON.parse(await readFile(join(RAW_DIR, file), 'utf8')) as {
      matches?: RawMatch[];
    };
    out.push({ key: file.replace(/^matches-|\.json$/g, ''), matches: body.matches ?? [] });
  }
  return out.sort((a, b) => a.key.localeCompare(b.key));
}

function crossTab(matches: RawMatch[]): Record<string, number> {
  return tally(matches, (match) => {
    const time = hasNoPublishedTime(match) ? 'no-time' : 'has-time';
    const nb = match.NotBeforeISOTime ? 'NotBeforeISO' : 'no-NotBeforeISO';
    const text = match.NotBeforeText ?? match.NotBefore ?? 'no-NotBeforeText';
    return `${time} | ${nb} | ${text}`;
  });
}

/** Which fields distinguish the two record shapes the feed mixes together. */
function shapeClusters(
  matches: RawMatch[],
): Record<string, { count: number; onlyFields: string[] }> {
  const byPulse = new Map<string, RawMatch[]>();
  for (const match of matches) {
    const key = match.PulseStatus ?? '(none)';
    byPulse.set(key, [...(byPulse.get(key) ?? []), match]);
  }
  const fieldSets = new Map<string, Set<string>>();
  for (const [key, group] of byPulse) {
    const fields = new Set<string>();
    for (const match of group) for (const field of Object.keys(match)) fields.add(field);
    fieldSets.set(key, fields);
  }
  const out: Record<string, { count: number; onlyFields: string[] }> = {};
  for (const [key, group] of byPulse) {
    const mine = fieldSets.get(key) ?? new Set<string>();
    const others = new Set<string>();
    for (const [otherKey, set] of fieldSets) {
      if (otherKey !== key) for (const field of set) others.add(field);
    }
    out[key] = { count: group.length, onlyFields: [...mine].filter((f) => !others.has(f)).sort() };
  }
  return out;
}

function competitorShapes(matches: RawMatch[]): Record<string, number> {
  return tally(matches, (match) => {
    if (match.PlayerTeam1 && match.PlayerTeam2) {
      const id = (match.PlayerTeam1 as { PlayerId?: string }).PlayerId ?? '';
      const partner = (match.PlayerTeam1 as { PartnerId?: unknown }).PartnerId;
      return `PlayerTeam1/2 | id=${id.startsWith('sr:') ? 'sr:competitor:N' : 'short-code'} | partner=${partner === null ? 'null(singles)' : partner === undefined ? 'absent' : 'present(doubles)'}`;
    }
    if (Array.isArray(match.TeamsInMatch)) return `TeamsInMatch[${match.TeamsInMatch.length}]`;
    return 'neither';
  });
}

function matchIdShapes(matches: RawMatch[]): Record<string, number> {
  return tally(matches, (match) => (match.MatchId ?? '').replace(/\d+/g, 'N'));
}

async function main(): Promise<void> {
  const loaded = await load();
  const all = loaded.flatMap((entry) => entry.matches);
  const out: string[] = [
    '# Tennis TV field semantics',
    '',
    '_Generated by `npm run recon:semantics` from `.recon-out/raw`._',
    '',
  ];

  out.push('## Identifier stability', '');
  const globalIds = uniqueness(all, (match) => match.MatchId);
  out.push(
    `- \`MatchId\` across every sampled tournament: **${globalIds.distinct} distinct / ${globalIds.total} records**, globally unique: **${globalIds.unique}**`,
  );
  if (!globalIds.unique) out.push(`  - duplicates: \`${globalIds.duplicates.join(', ')}\``);
  out.push(`- \`MatchId\` shapes: \`${JSON.stringify(matchIdShapes(all))}\``);
  const withTournament = uniqueness(all, (match) =>
    match.MatchId ? `${match.TournamentId}:${match.TournamentYear}:${match.MatchId}` : undefined,
  );
  out.push(
    `- \`TournamentId:TournamentYear:MatchId\` unique: **${withTournament.unique}** ` +
      `(${withTournament.distinct}/${withTournament.total})`,
    '',
  );

  out.push('## Start-time representation', '');
  out.push('Cross-tabulation of `MatchDate` time-of-day against the NotBefore fields:', '');
  out.push('```json');
  out.push(JSON.stringify(crossTab(all), null, 2));
  out.push('```', '');
  const noTime = all.filter(hasNoPublishedTime);
  out.push(
    `- records with **no published start time** (missing \`MatchDate\` or midnight time-of-day): **${noTime.length} / ${all.length}**`,
  );
  out.push(
    `- of those, carrying \`NotBeforeISOTime\`: **${noTime.filter((m) => m.NotBeforeISOTime).length}**`,
  );
  out.push(
    `- \`NotBeforeISOTime\` example values: \`${JSON.stringify([...new Set(all.map((m) => m.NotBeforeISOTime).filter(Boolean))].slice(0, 6))}\``,
  );
  out.push(
    `- \`NotBeforeText\`/\`NotBefore\` values: \`${JSON.stringify(tally(all, (m) => m.NotBeforeText ?? m.NotBefore))}\``,
    '',
  );
  const withTime = all.filter((m) => !hasNoPublishedTime(m));
  out.push(
    `- records **with** a published time that ALSO carry \`NotBeforeISOTime\`: **${withTime.filter((m) => m.NotBeforeISOTime).length}**`,
    '',
  );

  out.push('## Status vocabulary (observed, not from the bundle)', '');
  out.push(`- \`Status\`: \`${JSON.stringify(tally(all, (m) => m.Status))}\``);
  out.push(`- \`PulseStatus\`: \`${JSON.stringify(tally(all, (m) => m.PulseStatus))}\``);
  out.push(`- \`Reason\`: \`${JSON.stringify(tally(all, (m) => m.Reason))}\``);
  out.push(
    `- \`Status\` × \`PulseStatus\`: \`${JSON.stringify(tally(all, (m) => `${m.Status}/${m.PulseStatus}`))}\``,
  );
  out.push(
    `- \`Status\` × \`Reason\` where a reason exists: \`${JSON.stringify(
      tally(
        all.filter((m) => m.Reason),
        (m) => `${m.Status}/${m.Reason}`,
      ),
    )}\``,
    '',
  );

  for (const status of ['CA', 'WO']) {
    const examples = all.filter((m) => m.Status === status).slice(0, 2);
    out.push(`### Example records with \`Status: "${status}"\``, '', '```json');
    out.push(JSON.stringify(examples.map(redact), null, 2));
    out.push('```', '');
  }

  out.push('## Record shapes mixed in one feed', '');
  out.push('```json');
  out.push(JSON.stringify(shapeClusters(all), null, 2));
  out.push('```', '');

  out.push('## Competitor representation', '');
  out.push('```json');
  out.push(JSON.stringify(competitorShapes(all), null, 2));
  out.push('```', '');

  out.push('## Per-tournament status/time profile', '');
  out.push('| Tournament key | Matches | Status | PulseStatus | no-time |');
  out.push('| --- | --- | --- | --- | --- |');
  for (const entry of loaded) {
    out.push(
      `| \`${entry.key}\` | ${entry.matches.length} | \`${JSON.stringify(tally(entry.matches, (m) => m.Status))}\` | \`${JSON.stringify(tally(entry.matches, (m) => m.PulseStatus))}\` | ${entry.matches.filter(hasNoPublishedTime).length} |`,
    );
  }
  out.push('');

  await writeFile(OUT_FILE, `${out.join('\n')}\n`);
  console.error(`[semantics] done → ${OUT_FILE}`);
}

/** Trims example records down to the fields this investigation is about. */
function redact(match: RawMatch): Record<string, unknown> {
  const keep = [
    'MatchId',
    'MatchDate',
    'NotBeforeISOTime',
    'NotBeforeText',
    'NotBefore',
    'Status',
    'PulseStatus',
    'Reason',
    'CourtName',
    'Round',
    'RoundId',
    'TournamentId',
    'TournamentYear',
    'ResultString',
    'WinningPlayerId',
  ];
  const out: Record<string, unknown> = {};
  for (const key of keep) if (match[key] !== undefined) out[key] = match[key];
  out._playerShape = match.PlayerTeam1
    ? 'PlayerTeam1/2'
    : match.TeamsInMatch
      ? 'TeamsInMatch'
      : 'none';
  return out;
}

await main();
